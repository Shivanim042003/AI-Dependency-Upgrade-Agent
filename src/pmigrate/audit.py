"""Audit an evaluator-owned test adaptation: surface what could make a task easier.

Heuristic, line-level. It does not decide anything; it lists changes a human must justify:
removed tests, net-removed assertions, changed exception types, changed expected literals, new
skips/xfails, and wholesale (non-mechanical) rewrites. The rationale column is for the reviewer.
"""
from __future__ import annotations

import re
from collections import defaultdict
from dataclasses import dataclass, field

from .policy import _parse_diff
from .tasks import TaskSpec

RAISES = re.compile(r"pytest\.raises\(\s*([\w.]+)")
ASSERT = re.compile(r"^\s*assert\b|\.assert\w+\(|\bself\.assert")
TEST_DEF = re.compile(r"^\s*(?:async\s+)?def\s+(test\w*)\(")
SKIP = re.compile(r"pytest\.mark\.(skip|skipif|xfail)|pytest\.(skip|xfail)\(|unittest\.skip")
# mechanical v1->v2 renames we expect to see in tests; lines that differ only by these are "mechanical"
MECH = [(r"\.parse_obj\(", ".model_validate("), (r"\.dict\(", ".model_dump("), (r"\.json\(", ".model_dump_json("),
        (r"\.copy\(", ".model_copy("), (r"\.schema\(", ".model_json_schema("), (r"\.parse_raw\(", ".model_validate_json(")]


def _norm(line: str) -> str:
    for a, b in MECH:
        line = re.sub(a, b, line)
    return re.sub(r"\s+", "", line)


@dataclass
class FileAudit:
    path: str
    added: int = 0
    removed: int = 0
    mechanical: int = 0                      # removed/added pairs equal after the known v1->v2 renames
    tests_removed: list = field(default_factory=list)
    asserts_removed: int = 0
    asserts_added: int = 0
    exception_changes: list = field(default_factory=list)
    literal_changes: list = field(default_factory=list)
    skips_added: list = field(default_factory=list)

    @property
    def flags(self) -> list:
        f = []
        if self.tests_removed:
            f.append(f"REMOVED TESTS: {', '.join(self.tests_removed[:6])}")
        if self.asserts_removed > self.asserts_added:
            f.append(f"NET ASSERTIONS REMOVED: {self.asserts_removed - self.asserts_added}")
        if self.exception_changes:
            f.append("EXCEPTION TYPE CHANGED: " + "; ".join(self.exception_changes[:4]))
        if self.literal_changes:
            f.append(f"EXPECTED VALUES CHANGED: {len(self.literal_changes)} (e.g. {self.literal_changes[0][:90]})")
        if self.skips_added:
            f.append("SKIP/XFAIL ADDED")
        return f


def audit_patch(patch: str) -> list[FileAudit]:
    out = []
    for f in _parse_diff(patch):
        a = FileAudit(f["b"] if not f["deleted"] else f["a"], len(f["added"]), len(f["removed"]))
        rem, add = f["removed"], f["added"]
        a.mechanical = len({_norm(x) for x in rem} & {_norm(x) for x in add})
        add_tests = {m.group(1) for x in add if (m := TEST_DEF.match(x))}
        a.tests_removed = [m.group(1) for x in rem if (m := TEST_DEF.match(x)) and m.group(1) not in add_tests]
        if f["deleted"]:
            a.tests_removed.append("(entire file deleted)")
        a.asserts_removed = sum(1 for x in rem if ASSERT.search(x))
        a.asserts_added = sum(1 for x in add if ASSERT.search(x))
        rr, ar = [m.group(1) for x in rem if (m := RAISES.search(x))], [m.group(1) for x in add if (m := RAISES.search(x))]
        if rr != ar and (rr or ar):
            a.exception_changes.append(f"{rr[:3]} -> {ar[:3]}")
        remset = {_norm(x) for x in rem}
        for x in add:
            if ASSERT.search(x) and re.search(r"[\"'\d]", x) and _norm(x) not in remset:
                a.literal_changes.append(x.strip())
        a.skips_added = [x.strip() for x in add if SKIP.search(x)]
        out.append(a)
    return out


def render_markdown(task: TaskSpec, audits: list[FileAudit]) -> str:
    L = [f"# Adaptation audit: `{task.id}`  (track: {task.track}, provisional: {task.provisional})\n",
         "Generated by `pmigrate audit-adaptation`. Flags are heuristics: a human must fill in the rationale and "
         "decide whether each change preserves the behaviour under evaluation. The same evaluator-owned adaptation is "
         "applied for `noop`, `bump-pydantic` and every agent variant, and verification re-applies it; the agent cannot edit it.\n"]
    if not audits:
        return "\n".join(L + ["No adaptation patch: tests run exactly as upstream at `base_sha`.\n"])
    tot = defaultdict(int)
    for a in audits:
        tot["files"] += 1; tot["added"] += a.added; tot["removed"] += a.removed; tot["mech"] += a.mechanical
        tot["flagged"] += bool(a.flags)
    L.append(f"{tot['files']} files, +{tot['added']}/-{tot['removed']} lines, {tot['mech']} mechanical v1->v2 renames, "
             f"**{tot['flagged']} files with flags**.\n")
    L.append("| file | +/- | mechanical | flags | reviewer rationale |\n|---|---|---|---|---|")
    for a in sorted(audits, key=lambda x: (-len(x.flags), x.path)):
        L.append(f"| `{a.path}` | +{a.added}/-{a.removed} | {a.mechanical} | {'<br>'.join(a.flags) or '-'} | TODO |")
    L.append("\n## Reviewer checklist\n- [ ] every flagged change is necessary for v2 semantics (not just easier)\n"
             "- [ ] no assertion was weakened or deleted without a replacement\n"
             "- [ ] expected-value changes match documented v2 behaviour (cite the migration guide section)\n"
             "- [ ] starting state still fails; human source-only patch still passes (`pmigrate prepare-task` recorded both)\n")
    return "\n".join(L) + "\n"
